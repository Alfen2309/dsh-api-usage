/**
 * Bundle src/client.js into the shipped client.js.
 *
 * The browser module loader executes the file as an IIFE that registers the
 * plugin factory, so the bundle keeps that shape and inlines ECharts (no CDN,
 * no runtime dependency). `require('react')` inside the factory is a parameter
 * of that factory, not a module import, so esbuild leaves it untouched.
 */
import { build } from 'esbuild'

const result = await build({
  entryPoints: ['src/client.js'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome110'],
  outfile: 'client.js',
  minify: true,
  legalComments: 'none',
  banner: {
    js: '/* dsh-api-usage client bundle — generated by `npm run build`; edit src/client.js instead. */',
  },
  metafile: true,
})

const outputs = result.metafile.outputs
for (const [file, info] of Object.entries(outputs)) {
  if (file.endsWith('client.js')) {
    console.log(`built ${file}: ${(info.bytes / 1024).toFixed(1)} KiB`)
  }
}
